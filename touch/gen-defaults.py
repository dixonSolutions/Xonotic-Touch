#!/usr/bin/env python3
"""Write touch_defaults.cfg from the touch settings table in the client QuakeC.

The touch settings are defined once, in Touch_DefineCvars
(qcsrc/client/touch_init.qc). The client QuakeC only runs in a match, so the
engine also needs them as cvars from the start, for the menu to show and
change them and for config.cfg to save them. This script turns that table
into a list of `seta` lines, exec'd from xonotic-client.cfg on every start:

  touch/gen-defaults.py           rewrite the cfg from the table
  touch/gen-defaults.py --check   exit 1 if the cfg differs from the table

Edit the table, never the cfg, and run this after. The client also compares
each default it registers with the one the engine has (Touch_RegisterCvar),
and says so in the console when the two differ.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PK3DIR = ROOT / "engine/data/xonotic-data.pk3dir"
TABLE = PK3DIR / "qcsrc/client/touch_init.qc"
VERSION = PK3DIR / "qcsrc/client/touch_init.qh"
OUT = PK3DIR / "touch_defaults.cfg"

ENTRY = re.compile(r'^\s*Touch_RegisterCvar\("([A-Za-z0-9_]+)",\s*"([^"]*)"\);')


def render():
    src = TABLE.read_text(encoding="utf-8")
    body = src[src.index("void Touch_DefineCvars(void)"):]
    body = body[:body.index("\n}\n")]
    entries = [m.groups() for m in map(ENTRY.match, body.splitlines()) if m]
    if not entries:
        sys.exit(f"gen-defaults: no Touch_RegisterCvar entries in {TABLE}")
    version = re.search(r"const float TOUCH_LAYOUT_VERSION = (\d+);", VERSION.read_text(encoding="utf-8"))
    if not version:
        sys.exit(f"gen-defaults: no TOUCH_LAYOUT_VERSION in {VERSION}")
    lines = [
        "// Touch control settings at their defaults. GENERATED by touch/gen-defaults.py",
        "// from Touch_DefineCvars in qcsrc/client/touch_init.qc: edit the table there,",
        "// then run the script. Exec'd from xonotic-client.cfg, before config.cfg, so",
        "// the menu can show and change these before the first match and config.cfg",
        "// keeps what the player set.",
    ]
    lines += [f'seta {name} "{value}"' for name, value in entries]
    # The schema of the settings saved alongside these. A fresh install has
    # nothing older to migrate (Touch_MigrateLayout); a saved layout or
    # config.cfg from an older build carries its own lower number.
    lines.append(f"seta touch_layout_version {version.group(1)}")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if sys.argv[1:] == ["--check"]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run touch/gen-defaults.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} matches the table")
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10)) - 5} settings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
