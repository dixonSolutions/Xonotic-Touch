#ifndef TOUCH_LUA_LIB_H
#define TOUCH_LUA_LIB_H

// require("xt.ui"): immediate-mode widgets and layout helpers for client mods
static const char tlua_lib_ui[] =
"-- xt.ui: immediate-mode widgets for client mods (require(\"xt.ui\")).\n"
"-- Call ui.begin() at the top of a \"hud\" or \"draw\" handler, then draw widgets;\n"
"-- each widget call both draws and answers (button -> clicked, toggle -> value).\n"
"-- Input is the first finger on the screen, else the mouse with MOUSE1.\n"
"local ui = {}\n"
"local draw = xt.draw\n"
"\n"
"ui.theme = {\n"
"  size = 14, pad = 8, gap = 6,\n"
"  panel = {0.05, 0.07, 0.10, 0.80},\n"
"  title = {0.20, 0.55, 0.95, 0.95},\n"
"  button = {0.16, 0.20, 0.26, 0.90},\n"
"  hover = {0.22, 0.30, 0.40, 0.95},\n"
"  press = {0.20, 0.55, 0.95, 0.95},\n"
"  text = {1, 1, 1, 1},\n"
"  dim = {0.70, 0.75, 0.80, 1},\n"
"  on = {0.25, 0.75, 0.40, 1},\n"
"  off = {0.45, 0.20, 0.20, 1},\n"
"}\n"
"local t = ui.theme\n"
"\n"
"local px, py, down, wasdown = -1, -1, false, false\n"
"local pressx, pressy = -1, -1\n"
"\n"
"function ui.begin()\n"
"  wasdown = down\n"
"  local f = xt.fingers()[1]\n"
"  if f then\n"
"    px, py, down = f.x, f.y, true\n"
"  else\n"
"    px, py = xt.mouse()\n"
"    down = xt.keydown(\"MOUSE1\")\n"
"  end\n"
"  if down and not wasdown then pressx, pressy = px, py end\n"
"end\n"
"\n"
"function ui.pointer() return px, py, down end\n"
"\n"
"function ui.inside(x, y, w, h, ax, ay)\n"
"  ax, ay = ax or px, ay or py\n"
"  return ax >= x and ay >= y and ax < x + w and ay < y + h\n"
"end\n"
"\n"
"-- released inside after being pressed inside\n"
"local function clicked(x, y, w, h)\n"
"  return wasdown and not down and ui.inside(x, y, w, h) and ui.inside(x, y, w, h, pressx, pressy)\n"
"end\n"
"\n"
"local function fill(x, y, w, h, c) draw.fill(x, y, w, h, c[1], c[2], c[3], c[4]) end\n"
"\n"
"function ui.text(x, y, s, size, c)\n"
"  c = c or t.text\n"
"  return draw.text(x, y, s, size or t.size, c[1], c[2], c[3], c[4])\n"
"end\n"
"\n"
"function ui.textcentered(x, y, w, h, s, size, c)\n"
"  size = size or t.size\n"
"  local tw = draw.textwidth(s, size)\n"
"  return ui.text(x + (w - tw) / 2, y + (h - size) / 2, s, size, c)\n"
"end\n"
"\n"
"function ui.panel(x, y, w, h, title)\n"
"  fill(x, y, w, h, t.panel)\n"
"  if title then\n"
"    local th = t.size + t.pad\n"
"    fill(x, y, w, th, t.title)\n"
"    ui.textcentered(x, y, w, th, title)\n"
"    return x + t.pad, y + th + t.pad, w - 2 * t.pad, h - th - 2 * t.pad\n"
"  end\n"
"  return x + t.pad, y + t.pad, w - 2 * t.pad, h - 2 * t.pad\n"
"end\n"
"\n"
"function ui.button(x, y, w, h, label)\n"
"  local c = t.button\n"
"  if ui.inside(x, y, w, h) then c = down and t.press or t.hover end\n"
"  fill(x, y, w, h, c)\n"
"  ui.textcentered(x, y, w, h, label)\n"
"  return clicked(x, y, w, h)\n"
"end\n"
"\n"
"function ui.toggle(x, y, w, h, label, value)\n"
"  if ui.button(x, y, w, h, \"\") then value = not value end\n"
"  local s = h * 0.5\n"
"  fill(x + w - s - t.pad, y + (h - s) / 2, s, s, value and t.on or t.off)\n"
"  ui.text(x + t.pad, y + (h - t.size) / 2, label)\n"
"  return value\n"
"end\n"
"\n"
"function ui.slider(x, y, w, h, label, value, min, max)\n"
"  fill(x, y, w, h, t.button)\n"
"  local frac = (value - min) / (max - min)\n"
"  frac = frac < 0 and 0 or (frac > 1 and 1 or frac)\n"
"  fill(x, y, w * frac, h, t.press)\n"
"  ui.text(x + t.pad, y + (h - t.size) / 2, string.format(\"%s  %.2f\", label, value))\n"
"  if down and ui.inside(x, y, w, h, pressx, pressy) then\n"
"    local f = (px - x) / w\n"
"    f = f < 0 and 0 or (f > 1 and 1 or f)\n"
"    value = min + f * (max - min)\n"
"  end\n"
"  return value\n"
"end\n"
"\n"
"-- rows inside a rectangle: local col = ui.column(x, y, w); local x, y, w, h = col:row(28)\n"
"function ui.column(x, y, w, gap)\n"
"  local c = {x = x, y = y, w = w, gap = gap or t.gap}\n"
"  function c:row(h)\n"
"    local ry = self.y\n"
"    self.y = self.y + h + self.gap\n"
"    return self.x, ry, self.w, h\n"
"  end\n"
"  return c\n"
"end\n"
"\n"
"-- columns across a row: ui.split(x, w, n, gap) -> list of {x, w}\n"
"function ui.split(x, w, n, gap)\n"
"  gap = gap or t.gap\n"
"  local cw, out = (w - gap * (n - 1)) / n, {}\n"
"  for i = 1, n do out[i] = {x + (i - 1) * (cw + gap), cw} end\n"
"  return out\n"
"end\n"
"\n"
"return ui\n"
"\n";

#endif
