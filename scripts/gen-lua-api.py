#!/usr/bin/env python3
"""Generate the Lua mod API glue and reference from scripts/lua_api_table.py.

  engine/darkplaces/touch_lua_api_gen.h   registration table (name, C function, tier,
                                          realm), the realms' event lists, and the
                                          Lua modules of engine/darkplaces/touch_lua_lib/
  docs/LUA_API.md                         the reference (with docs/lua_api_notes.md)

  python3 scripts/gen-lua-api.py           # write
  python3 scripts/gen-lua-api.py --check   # exit 1 when stale or when the C code
                                           # and the table disagree

The check also makes sure every "legacy" entry is still registered by the C code
(TLua_SetField(L, "<name>", <function>)), that every TLuaAPI_ function the table
names is defined, and that the server event list in touch_lua_sv.c is the table's.
"""
import glob
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import lua_api_table as T  # noqa: E402

DP = os.path.join(ROOT, "engine/darkplaces")
OUT_H = os.path.join(DP, "touch_lua_api_gen.h")
OUT_MD = os.path.join(ROOT, "docs/LUA_API.md")
NOTES = os.path.join(ROOT, "docs/lua_api_notes.md")
LIBDIR = os.path.join(DP, "touch_lua_lib")
TIERBIT = {"standard": "TLUA_TIER_STANDARD", "gamerules": "TLUA_TIER_GAMERULES", "internet": "TLUA_TIER_INTERNET", "engine_full": "TLUA_TIER_ENGINE"}
REALM = {"both": 3, "client": 1, "server": 2}


def cname(e):
    return "TLuaAPI_" + ("sv_" if e["realm"] == "server" else "cl_" if e["realm"] == "client" else "") + e["name"].replace(".", "_")


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def gen_h():
    out = ["// Generated by scripts/gen-lua-api.py from scripts/lua_api_table.py. Do not edit.",
           "#ifndef TOUCH_LUA_API_GEN_H", "#define TOUCH_LUA_API_GEN_H", "",
           "// realm: 1 client, 2 server, 3 both",
           "typedef struct tlua_apidef_s { const char *module; const char *name; lua_CFunction fn; unsigned tier; unsigned char realm; } tlua_apidef_t;", ""]
    new = [e for e in T.API if e["impl"] == "c"]
    for e in new:
        out.append(f"int {cname(e)}(lua_State *L);")
    out += ["", "#ifdef TLUA_API_DEFINE_TABLE", "static const tlua_apidef_t tlua_apidefs[] = {"]
    for e in new:
        mod, _, nm = e["name"].rpartition(".")
        out.append(f"\t{{{c_str(mod) if mod else 'NULL'}, {c_str(nm)}, {cname(e)}, {TIERBIT[e['tier']]}, {REALM[e['realm']]}}},")
    out += ["\t{NULL, NULL, NULL, 0, 0}", "};", "#endif", ""]
    for realm in ("client", "server"):
        names = ", ".join(c_str(ev[0]) for ev in T.EVENTS[realm])
        out.append(f"#define TLUA_{'CL' if realm == 'client' else 'SV'}_EVENTS_GEN {names}, NULL")
    out.append("")
    out.append("// client hooks a client mod may change and cancel without Game rules (its own screen)")
    out.append("static const char *const tlua_cl_hooks_writable[] = {" + ", ".join(c_str(n) for n in sorted(T.CLIENT_WRITABLE)) + ", NULL};")
    out.append("")
    for path in sorted(glob.glob(os.path.join(LIBDIR, "*.lua"))):
        base = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding="utf-8") as f:
            src = f.read()
        out.append(f"// {os.path.relpath(path, ROOT)}")
        out.append(f"static const char tlua_lib_{base}[] =")
        for line in src.split("\n")[:-1] if src.endswith("\n") else src.split("\n"):
            out.append("\t" + c_str(line + "\n"))
        out.append("\t;")
        out.append("")
    out += ["#endif", ""]
    return "\n".join(out)


PUB = {"yes": "yes", "godnotic-csqc": "with this game's client code", "offline": "limited online (see doc)", "host": "games you host"}


def esc(s):
    return s.replace("|", "\\|")


def gen_md():
    out = ["# Lua mod API reference", "",
           "<!-- Generated by scripts/gen-lua-api.py from scripts/lua_api_table.py and docs/lua_api_notes.md. Do not edit. -->", ""]
    counts = {r: sum(1 for e in T.API if e["realm"] == r) for r in ("both", "client", "server")}
    out.append(f"API level **3**. {len(T.API)} functions: {counts['both']} in both realms, {counts['client']} for client mods, "
               f"{counts['server']} for server mods; {len(T.EVENTS['client'])} client events and {len(T.EVENTS['server'])} server events; "
               "the game's hooks are in [LUA_HOOKS.md](LUA_HOOKS.md). Start with [MODDING.md](MODDING.md); recipes are in "
               "[MOD_COOKBOOK.md](MOD_COOKBOOK.md).")
    out.append("")
    out.append("## Tiers")
    out.append("")
    out.append("| Tier | How it is turned on | What it allows |")
    out.append("|---|---|---|")
    for name, how, what in T.TIERS:
        out.append(f"| `{name}` | {how} | {what} |")
    out.append("")
    out.append("A mod can use a tier only when its `mod.txt` **declares** it (`permissions:`; `standard` is implied) **and** "
               "the player **granted** it: declared ∩ granted, checked on every call, so a revoke fails the next call and "
               "nothing undeclared can be granted. A folder without `mod.txt` gets the standard tier only. See "
               "[MODDING.md](MODDING.md), *Permissions: declare, explain, get granted*.")
    out.append("")
    titles = {"both": "Both realms", "client": "Client mods", "server": "Server mods"}
    for realm in ("both", "client", "server"):
        out.append(f"## {titles[realm]}")
        out.append("")
        out.append("| Function | Tier | Works | Web | Limits | What it does |")
        out.append("|---|---|---|---|---|---|")
        for e in T.API:
            if e["realm"] != realm:
                continue
            out.append(f"| `{esc(e['sig'])}` | {e['tier']} | {PUB[e['public']]} | {'yes' if e['web'] else 'no'} | {esc(e['limits']) or '-'} | {esc(e['doc'])} |")
        out.append("")
    for realm in ("client", "server"):
        out.append(f"## Events: {titles[realm].lower()}")
        out.append("")
        out.append("`xt.on(name, function(...) ... end)`. | Event | Arguments | When | Works |")
        out[-1] = "`xt.on(name, function(...) ... end)`"
        out.append("")
        out.append("| Event | Arguments | When | Works |")
        out.append("|---|---|---|---|")
        for name, args, when, pub in T.EVENTS[realm]:
            out.append(f"| `{name}` | {args or '-'} | {esc(when)} | {PUB[pub]} |")
        out.append("")
    with open(NOTES, encoding="utf-8") as f:
        out.append(f.read().rstrip("\n"))
    out.append("")
    return "\n".join(out)


def check_code():
    problems = []
    src = {}
    for p in glob.glob(os.path.join(DP, "touch_lua*.c")):
        with open(p, encoding="utf-8") as f:
            src[os.path.basename(p)] = f.read()
    allsrc = "\n".join(src.values())
    for e in T.API:
        if e["impl"].startswith("legacy:"):
            fn = e["impl"].split(":", 1)[1]
            last = e["name"].rpartition(".")[2]
            if not re.search(r'TLua_SetField\(L,\s*"%s",\s*%s\)' % (re.escape(last), re.escape(fn)), allsrc):
                problems.append(f"xt.{e['name']}: no TLua_SetField(L, \"{last}\", {fn}) in engine/darkplaces/touch_lua*.c")
        elif e["impl"] == "c":
            if not re.search(r"\bint %s\(lua_State \*L\)\s*\{" % cname(e), allsrc):
                problems.append(f"xt.{e['name']}: {cname(e)} is not defined in engine/darkplaces/touch_lua*.c")
    sv = src.get("touch_lua_sv.c", "")
    m = re.search(r"tlua_sv_events\[\]\s*=\s*\{(.*?)\};", sv, re.S)
    if m and "TLUA_SV_EVENTS_GEN" not in m.group(1):
        names = re.findall(r'"(\w+)"', m.group(1))
        want = [ev[0] for ev in T.EVENTS["server"]]
        if names != want:
            problems.append(f"server events in touch_lua_sv.c {names} differ from the table {want}")
    return problems


def main():
    check = "--check" in sys.argv[1:]
    files = {OUT_H: gen_h(), OUT_MD: gen_md()}
    stale = []
    for path, text in files.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    problems = check_code()
    for p in problems:
        print("api table: " + p)
    if check and stale:
        print("stale (run scripts/gen-lua-api.py): " + ", ".join(stale))
    if (check and stale) or problems:
        return 1
    n = len(T.API)
    print(f"{n} functions, {len(T.EVENTS['client'])}+{len(T.EVENTS['server'])} events; " +
          ("generated files up to date" if check else "wrote " + (", ".join(stale) if stale else "nothing (up to date)")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
