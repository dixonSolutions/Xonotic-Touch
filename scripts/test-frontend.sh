#!/bin/bash
# The native front-end bridge (engine/darkplaces/touch_frontend.c,
# docs/FRONTEND_BRIDGE.md), headless, one check per topic: what the Android
# app's Kotlin screens read (fe_dump / fe_take print the JSON the bridge would
# hand them) and the intents they send (`fe ...`), on real engines.
#
#   BASEDIR=<basedir with data/*.pk3 and the Touch xonotic-data.pk3dir> scripts/test-frontend.sh
# Optional: ENGINE (default build/bin/xonotic, else engine/darkplaces/darkplaces-sdl),
# OUT (keep logs), LD_LIBRARY_PATH for a libjpeg.so.62 the engine dlopens,
# MAP (default stormkeep).
#
# Two engines on the loopback: a LAN game hosted through `fe host` with a
# join password, and a client that finds it (as a favourite: loopback has no
# broadcast) and joins through `fe password`, wrong password first.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENGINE="${ENGINE:-$ROOT/build/bin/xonotic}"
[ -x "$ENGINE" ] || ENGINE="$ROOT/engine/darkplaces/darkplaces-sdl"
BASEDIR="${BASEDIR:?set BASEDIR to a Xonotic basedir (data/*.pk3 plus the Touch pk3dir)}"
MAP="${MAP:-stormkeep}"
PORT=26093
WORK="$(mktemp -d "${TMPDIR:-/tmp}/xt-fe.XXXXXX")"
cleanup() {
	[ -n "${HOSTPID:-}" ] && kill "$HOSTPID" 2> /dev/null
	if [ -n "${OUT:-}" ]; then mkdir -p "$OUT" && cp "$WORK"/*.log "$OUT/" 2> /dev/null; fi
	rm -rf "$WORK"
}
trap cleanup EXIT

fail=0
ok() { echo "ok   $*"; }
bad() { echo "FAIL $*"; fail=1; }
# expect <log> <description> <grep -E pattern>
expect() { if grep -qE -- "$3" "$1"; then ok "$2"; else bad "$2"; fi; }
refuse() { if grep -qE -- "$3" "$1"; then bad "$2"; else ok "$2"; fi; }

run_engine() { # name seconds cfg-text extra-args...
	local name=$1 secs=$2 cfg=$3
	shift 3
	local ud="$WORK/$name"
	mkdir -p "$ud/data"
	printf '%s\n' "$cfg" > "$ud/data/fe_test.cfg"
	env SDL_VIDEODRIVER=offscreen SDL_AUDIODRIVER=dummy timeout "$secs" "$ENGINE" -xonotic -nosound \
		-basedir "$BASEDIR" -userdir "$ud" +vid_width 640 +vid_height 400 +vid_fullscreen 0 \
		+sys_colortranslation 2 +set touch_native_frontend 1 "$@" +exec fe_test.cfg > "$WORK/$name.log" 2>&1
}

# --- 1. topics, attach, heartbeat, the schema, intents' encoding
run_engine topics 90 "
fe_dump app
fe_dump gametypes
fe_dump maps
fe_dump player
fe_dump lan
fe_dump mods
fe preview $MAP
fe_take
echo STEP state-before-attach \$_fe_state
fe attach 1
fe beat
echo STEP state-attached \$_fe_state
fe watch _cl_name sensitivity rcon_password _cl_touch_lan_password vid_conwidth
fe set _cl_name Tester%20%22One%22%3Bquit
fe set rcon_password secret
fe set _cl_touch_lan_password secret
fe set touch_lan_hosting 1
fe_dump cvars
fe_dump player
fe screen home 2
set touch_native_frontend 0
echo STEP state-switch-off \$_fe_state
set touch_native_frontend 1
fe beat
fe menu qcmenu
echo STEP state-advanced \$_fe_state
fe menu native
fe beat
echo STEP state-native \$_fe_state
defer 6 \"echo STEP state-stale \$\$_fe_state; fe beat\"
defer 7 \"echo STEP state-beat-again \$\$_fe_state; fe detach; echo STEP state-detached \$\$_fe_state; fe_take; quit\"
"
L="$WORK/topics.log"
expect "$L" "app topic: protocol 1, enabled, in the menu" '^FE app \{"proto":1,"enabled":true,"attached":false,.*"state":"menu"'
expect "$L" "gametypes: Deathmatch and CTF with their cvars" '^FE gametypes .*"id":"dm","cvar":"g_dm","title":"Deathmatch".*"id":"ctf","cvar":"g_ctf"'
expect "$L" "maps: $MAP from its mapinfo, with modes" "^FE maps .*\"name\":\"$MAP\",\"title\":\"[^\"]+\".*\"types\":\"dm "
refuse "$L" "maps: no autogenerated or bsp-less entries" '"name":"autogenerated'
expect "$L" "player topic" '^FE player \{"name":'
expect "$L" "lan topic: available, the Host screen's settings" '^FE lan \{"available":true,"hosting":false.*"host_port":[0-9]+'
refuse "$L" "lan topic: no password values" '^FE lan .*"touch_lan_host_password":'
expect "$L" "mods topic: the manager's cvars" '^FE mods \{"mods":".*"install":'
expect "$L" "preview: the map picture copied out of its pack" "^FE preview \{\"ref\":\"$MAP\",\"path\":\"/.*fe_cache/maps_$MAP\\.(jpg|png)\"\}"
expect "$L" "not attached: the QuakeC menu is in charge (_fe_state 0)" '^STEP state-before-attach 0'
expect "$L" "attached and beating: the native UI owns the menu (_fe_state 1)" '^STEP state-attached 1'
expect "$L" "a percent-encoded name arrives whole, quotes and ; included" '^FE cvars .*"_cl_name":"Tester \\"One\\";quit"'
refuse "$L" "private cvars are not readable" '^FE cvars .*(rcon_password|_cl_touch_lan_password)'
refuse "$L" "private cvar values never appear" 'secret'
expect "$L" "private cvars are not writable" 'fe set: rcon_password is not in the front-end schema'
expect "$L" "read-only cvars are not writable" 'fe set: touch_lan_hosting is not in the front-end schema'
expect "$L" "touch_native_frontend 0: the QuakeC menu takes over (_fe_state 2)" '^STEP state-switch-off 2'
expect "$L" "Advanced: the QuakeC menu handed back on purpose (_fe_state 2)" '^STEP state-advanced 2'
expect "$L" "back to native (_fe_state 1)" '^STEP state-native 1'
expect "$L" "no heartbeat for 4 s: the QuakeC menu takes over by itself (_fe_state 2)" '^STEP state-stale 2'
expect "$L" "a heartbeat again: native again (_fe_state 1)" '^STEP state-beat-again 1'
expect "$L" "detach: the QuakeC menu is in charge (_fe_state 0)" '^STEP state-detached 0'
expect "$L" "refusals are events for the UI" '^FE event \{"type":"refused","cvar":"rcon_password"\}'
expect "$L" "the engine did not run the ;quit inside the name" '^STEP state-detached'

# --- 2. a local bot match: play, pause (the hidden QuakeC game menu), resume, leave
run_engine play 150 "
set fe_echo 1
fe attach 1
fe beat
fe play dm $MAP 2 3 5 10
alias fe_poll \"fe beat; defer 1 fe_poll\"
fe_poll
defer 40 \"fe_dump app; menu_showgamemenudialog\"
defer 42 \"fe_dump app; echo STEP paused-fe-state \$\$_fe_state; fe menu resume\"
defer 44 \"fe_dump app; fe menu leave\"
defer 48 \"fe_dump app; quit\"
"
L="$WORK/play.log"
expect "$L" "fe play: a local match of the mode on the map" "^FE app .*\"state\":\"ingame\",\"menu\":false,.*\"local\":true.*\"map\":\"$MAP\""
expect "$L" "the loading screen's progress reaches the connect topic" '^FE> connect .*"stage":"(loading|signon)".*"load":"[^"]+"'
expect "$L" "pause (the HUD MENU: menu_showgamemenudialog): the game menu opens hidden, the local game pauses" '^FE app .*"owns_menu":true.*"state":"paused","menu":true.*"paused":true'
expect "$L" "the paused menu stays the native UI's (_fe_state 1)" '^STEP paused-fe-state 1'
expect "$L" "resume" '^FE app .*"state":"ingame".*"paused":false'
expect "$L" "leave: back to the menu" '^FE app .*"state":"menu","menu":true,.*"local":false'

# --- 3. hosting through fe host with a password, joining through fe password
run_engine host 120 "
fe attach 1
alias fe_poll \"fe beat; defer 1 fe_poll\"
fe_poll
fe sub lan 1
fe screen host 0
fe host Bridge%20test dm $MAP 1 6 $PORT 7 open%20sesame 0
defer 25 \"fe_dump lan; fe_dump app\"
defer 65 \"fe_dump lan\"
defer 100 \"fe_dump lan; quit\"
" &
HOSTPID=$!
sleep 30
run_engine join 70 "
fe attach 1
alias fe_poll \"fe beat; defer 1 fe_poll\"
fe_poll
fe screen multiplayer 0
fe favorite 127.0.0.1:$PORT 1
fe refresh internet
defer 6 \"fe_dump servers; fe connect 127.0.0.1:$PORT\"
defer 12 \"fe_take; fe password 127.0.0.1:$PORT wrong 0\"
defer 18 \"fe_take; fe password 127.0.0.1:$PORT open%20sesame 0\"
defer 45 \"fe_dump app; fe_take; fe menu leave\"
defer 48 \"quit\"
"
wait "$HOSTPID"
HOSTPID=
L="$WORK/host.log"
expect "$L" "fe host: hosting on purpose, on the port asked" "^FE lan .*\"hosting\":true,\"on_purpose\":true,\"port\":$PORT"
expect "$L" "fe host: the password is armed (set flag only, no value)" '^FE lan .*"password_set":(true|false)'
refuse "$L" "the join password never appears in a snapshot" 'open sesame'
expect "$L" "the host saw the wrong password" 'wrong join password'
expect "$L" "the client joined the host" '^FE lan .*"others":1'
L="$WORK/join.log"
expect "$L" "servers topic: the favourite answered, locked, on the LAN" "FE servers .*\"a\":\"127.0.0.1:$PORT\",\"n\":\"Bridge test\".*\"l\":true,\"f\":true,\"lan\":true"
expect "$L" "a locked game asks for the password (event)" '^FE event \{"type":"password","kind":"required","address":"127.0.0.1:'"$PORT"'"\}'
expect "$L" "a wrong password says so (event)" '^FE event \{"type":"password","kind":"wrong","address":"127.0.0.1:'"$PORT"'"\}'
expect "$L" "the right password joins: in the game" "^FE app .*\"state\":\"ingame\".*\"local\":false.*\"map\":\"$MAP\",\"server\":\"127.0.0.1:$PORT\""
refuse "$L" "the join password never appears in a snapshot" 'open sesame'

[ "$fail" = 0 ] && echo "front-end bridge: all checks passed" || echo "front-end bridge: FAILED"
exit "$fail"
